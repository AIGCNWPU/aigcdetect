def _check_visual_marker(
    cfg: dict[str, Any], frame: dict[str, Any]
) -> dict[str, Any]:
    body = _post_completion(cfg, _build_visual_marker_messages(frame))
    try:
        content = body["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise RuntimeError("视觉模型返回格式异常") from exc
    data = _parse_payload(content)
    found = data.get("marker_found")
    if isinstance(found, str):
        found = found.strip().lower() == "true"
    if found is not True and found != 1:
        return {"found": False}
    try:
        confidence = _to_probability(data.get("confidence"))
    except (TypeError, ValueError):
        confidence = 0.0
    return {
        "found": True,
        "text": _clean_marker_text(data.get("marker_text")),
        "location": _clean_marker_text(data.get("location")),
        "confidence": confidence,
    }


