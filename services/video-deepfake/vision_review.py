def load_config() -> dict[str, Any]:
    """读取环境变量与 .env；环境变量优先，每次检测重新读取。"""
    file_values = _read_env_file()

    def get(name: str, default: str = "") -> str:
        return (os.environ.get(name) or file_values.get(name) or default).strip()

    def get_int(name: str, default: int, lower: int, upper: int) -> int:
        try:
            return max(lower, min(upper, int(get(name, str(default)))))
        except ValueError:
            return default

    def get_float(name: str, default: float, lower: float, upper: float) -> float:
        try:
            return max(lower, min(upper, float(get(name, str(default)))))
        except ValueError:
            return default

    def get_bool(name: str, default: bool) -> bool:
        value = get(name, "on" if default else "off").lower()
        return value not in {"0", "false", "off", "no", "disabled"}

    mode = get("DEEPSEEK_REVIEW_MODE", DEFAULT_MODE).lower()
    if mode not in {"off", "low", "always"}:
        mode = DEFAULT_MODE
    try:
        timeout = float(get("DEEPSEEK_TIMEOUT", str(DEFAULT_TIMEOUT)))
    except ValueError:
        timeout = DEFAULT_TIMEOUT
    medium = get_float(
        "DEEPSEEK_MEDIUM_THRESHOLD", DEFAULT_MEDIUM_THRESHOLD, 0.05, 0.95
    )
    high = get_float(
        "DEEPSEEK_HIGH_THRESHOLD", DEFAULT_HIGH_THRESHOLD, medium, 1.0
    )
    return {
        "api_key": get("DEEPSEEK_API_KEY"),
        "base_url": get("DEEPSEEK_BASE_URL", DEFAULT_BASE_URL).rstrip("/"),
        "model": get("DEEPSEEK_VISION_MODEL", DEFAULT_MODEL),
        "mode": mode,
        "timeout": max(5.0, timeout),
        "max_frames": get_int("DEEPSEEK_MAX_FRAMES", DEFAULT_MAX_FRAMES, 1, 6),
        "workers": get_int("DEEPSEEK_WORKERS", DEFAULT_WORKERS, 1, 8),
        "medium_threshold": medium,
        "high_threshold": high,
        "explain_segments": get_bool("DEEPSEEK_EXPLAIN_SEGMENTS", True),
        "max_segments": get_int("DEEPSEEK_MAX_SEGMENTS", DEFAULT_MAX_SEGMENTS, 0, 30),
        "explain_frames": get_int("DEEPSEEK_EXPLAIN_FRAMES", DEFAULT_EXPLAIN_FRAMES, 1, 4),
        "explain_workers": get_int("DEEPSEEK_EXPLAIN_WORKERS", DEFAULT_EXPLAIN_WORKERS, 1, 8),
        "visual_marker": get_bool("DEEPSEEK_VISUAL_MARKER", True),
        "visual_marker_frames": get_int(
            "DEEPSEEK_VISUAL_MARKER_FRAMES", DEFAULT_VISUAL_MARKER_FRAMES, 1, 12
        ),
        "visual_marker_workers": get_int(
            "DEEPSEEK_VISUAL_MARKER_WORKERS", DEFAULT_VISUAL_MARKER_WORKERS, 1, 8
        ),
        "visual_marker_confidence": get_float(
            "DEEPSEEK_VISUAL_MARKER_CONFIDENCE",
            DEFAULT_VISUAL_MARKER_CONFIDENCE,
            0.1,
            0.99,
        ),
    }


def _read_env_file() -> dict[str, str]:
    path = Path(os.environ.get("DEEPSEEK_ENV_FILE") or ENV_FILE)
    values: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return values
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if key.startswith("DEEPSEEK_"):
            values[key] = value
    return values


def review_result(result: dict[str, Any], config: dict[str, Any] | None = None) -> dict[str, Any]:
    """在本地结果上叠加视觉复核；任何异常都回退到原结果。"""
    if not isinstance(result, dict):
        return result
    meta = result.get("meta")
    if not isinstance(meta, dict):
        meta = {}
        result["meta"] = meta

    persons = [item for item in (result.get("persons") or []) if isinstance(item, dict)]
    cfg = config or load_config()
    existing = meta.get("review")
    if isinstance(existing, dict) and existing.get("status") in {"ok", "partial"}:
        return result
    if cfg["mode"] == "off":
        meta["review"] = _status(cfg, "disabled")
        return result
    if not cfg.get("api_key"):
        meta["review"] = _status(cfg, "not_configured")
        return result
    if cfg["mode"] == "low" and str(result.get("risk") or "unknown") != "low":
        meta["review"] = _status(cfg, "skipped", reason="local_risk_not_low")
        return result

    frames = _select_frames(persons, int(cfg["max_frames"]))
    if not frames:
        meta["review"] = _status(cfg, "skipped", reason="no_frames")
        return result

    started = time.perf_counter()
    reviews: dict[str, dict[str, Any]] = {}
    errors: list[str] = []
    workers = min(int(cfg["workers"]), len(frames))
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {pool.submit(_review_frame, cfg, frame): frame for frame in frames}
        for future in as_completed(futures):
            frame = futures[future]
            try:
                reviews[str(frame.get("id"))] = future.result()
            except Exception as exc:  # 单张失败不影响其余帧
                message = _safe_error(exc)
                errors.append(message)
                log.warning("视觉复核失败 frame=%s：%s", frame.get("id"), message)

    elapsed_ms = round((time.perf_counter() - started) * 1000)
    if not reviews:
        meta["review"] = _status(
            cfg,
            "failed",
            requested=len(frames),
            succeeded=0,
            failed=len(frames),
            durationMs=elapsed_ms,
            error=errors[0] if errors else "",
        )
        result["summary"] = _append_text(
            result.get("summary"), "视觉复核未完成，本次结论仅基于本地检测。", 4000
        )
        findings = _strings(result.get("findings"))
        result["findings"] = (findings + ["视觉复核未完成，本次结论仅基于本地检测。"])[:12]
        return result

    flagged, escalated = _merge_reviews(result, persons, reviews, cfg)
    failed = len(frames) - len(reviews)
    if failed:
        result["summary"] = _append_text(
            result.get("summary"),
            f"另有 {failed} 张代表画面复核未完成。",
            4000,
        )
    status = "ok" if not failed else "partial"
    meta["review"] = _status(
        cfg,
        status,
        requested=len(frames),
        succeeded=len(reviews),
        failed=failed,
        flagged=flagged,
        escalated=escalated,
        durationMs=elapsed_ms,
        error=errors[0] if errors else "",
    )
    return result


def explain_segments(
    result: dict[str, Any], config: dict[str, Any] | None = None
) -> dict[str, Any]:
    """为可疑时间段生成一句视觉复核说明；失败时保留原说明。"""
    if not isinstance(result, dict):
        return result
    meta = result.get("meta")
    if not isinstance(meta, dict):
        meta = {}
        result["meta"] = meta

    cfg = config or load_config()
    existing = meta.get("explanation")
    if isinstance(existing, dict) and existing.get("status") in {"ok", "partial"}:
        return result
    if cfg.get("mode") == "off":
        meta["explanation"] = _status(cfg, "disabled")
        return result
    if not cfg.get("explain_segments"):
        meta["explanation"] = _status(cfg, "disabled", reason="explanation_off")
        return result
    if not cfg.get("api_key"):
        meta["explanation"] = _status(cfg, "not_configured")
        return result

    persons = [item for item in (result.get("persons") or []) if isinstance(item, dict)]
    targets = _select_explanation_targets(persons, int(cfg["max_segments"]))
    if not targets:
        meta["explanation"] = _status(cfg, "skipped", reason="no_segments")
        return result

    jobs = []
    missing = 0
    for person, segment in targets:
        frames = _frames_for_segment(person, segment, int(cfg["explain_frames"]))
        if frames:
            jobs.append((person, segment, frames))
        else:
            missing += 1
            log.warning("可疑片段 %s 没有可用人脸画面，跳过解释", segment.get("id"))
    if not jobs:
        meta["explanation"] = _status(
            cfg,
            "skipped",
            requested=len(targets),
            succeeded=0,
            failed=missing,
            missingFrames=missing,
            reason="no_frames",
        )
        return result

    started = time.perf_counter()
    explanations: dict[str, str] = {}
    errors: list[str] = []
    workers = min(int(cfg["explain_workers"]), len(jobs))
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {
            pool.submit(_explain_segment, cfg, segment, frames): (person, segment, frames)
            for person, segment, frames in jobs
        }
        for future in as_completed(futures):
            _, segment, _ = futures[future]
            try:
                text = future.result()
            except Exception as exc:
                message = _safe_error(exc)
                errors.append(message)
                log.warning("可疑片段解释失败 segment=%s：%s", segment.get("id"), message)
                continue
            if text:
                explanations[str(segment.get("id"))] = text

    elapsed_ms = round((time.perf_counter() - started) * 1000)
    failed = len(jobs) - len(explanations) + missing
    if not explanations:
        meta["explanation"] = _status(
            cfg,
            "failed",
            requested=len(targets),
            succeeded=0,
            failed=failed,
            missingFrames=missing,
            durationMs=elapsed_ms,
            error=errors[0] if errors else "",
        )
        return result

    for person, segment, _ in jobs:
        text = explanations.get(str(segment.get("id")))
        if text:
            segment["explanation"] = text
    _merge_explanations(result, jobs, explanations)
    meta["explanation"] = _status(
        cfg,
        "ok" if not failed else "partial",
        requested=len(targets),
        succeeded=len(explanations),
        failed=failed,
        missingFrames=missing,
        durationMs=elapsed_ms,
        error=errors[0] if errors else "",
    )
    return result


def _select_explanation_targets(
    persons: list[dict[str, Any]], limit: int
) -> list[tuple[dict[str, Any], dict[str, Any]]]:
    if limit <= 0:
        return []
    targets = []
    for person in persons:
        for segment in person.get("segments") or []:
            if isinstance(segment, dict) and segment.get("risk") in {"medium", "high"}:
                targets.append((person, segment))
    targets.sort(
        key=lambda item: (
            -RISK_LEVELS.get(str(item[1].get("risk") or "low"), 0),
            _float(item[1].get("start")),
        )
    )
    return targets[:limit]


def _frames_for_segment(
    person: dict[str, Any], segment: dict[str, Any], limit: int
) -> list[dict[str, Any]]:
    frames = [frame for frame in person.get("frames") or [] if _valid_frame(frame)]
    if not frames:
        return []
    start = _float(segment.get("start"))
    end = _float(segment.get("end"))
    frame_id = str(segment.get("frameId") or "")
    linked = next((frame for frame in frames if str(frame.get("id")) == frame_id), None)
    in_range = [
        frame
        for frame in frames
        if start - 0.05 <= _float(frame.get("time")) <= end + 0.05
    ]
    candidates = []
    seen = set()
    for frame in ([linked] if linked else []) + in_range:
        key = str(frame.get("id"))
        if key not in seen:
            seen.add(key)
            candidates.append(frame)
    if not candidates:
        midpoint = (start + end) / 2.0
        candidates = [
            min(frames, key=lambda frame: abs(_float(frame.get("time")) - midpoint))
        ]
    candidates.sort(key=lambda frame: _float(frame.get("time")))
    if len(candidates) <= limit:
        return candidates
    if limit <= 1:
        return [candidates[len(candidates) // 2]]
    indexes = sorted(
        {round(index * (len(candidates) - 1) / (limit - 1)) for index in range(limit)}
    )
    return [candidates[index] for index in indexes]


def _explain_segment(
    cfg: dict[str, Any], segment: dict[str, Any], frames: list[dict[str, Any]]
) -> str:
    body = _post_completion(cfg, _build_explanation_messages(segment, frames))
    try:
        content = body["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise RuntimeError("视觉模型返回格式异常") from exc
    text = _clean_explanation(content)
    if not text:
        raise RuntimeError("视觉模型返回空解释")
    return text


def _build_explanation_messages(
    segment: dict[str, Any], frames: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    start = _float(segment.get("start"))
    end = _float(segment.get("end"))
    risk_label = {"high": "高风险", "medium": "中风险"}.get(
        str(segment.get("risk") or ""), "可疑"
    )
    content: list[dict[str, Any]] = [
        {
            "type": "text",
            "text": (
                f"检测模型把视频 {start:.1f}s–{end:.1f}s 的人脸片段标记为{risk_label}片段。"
                "请根据以下人脸画面，只依据画面中可见的内容，用一句中文（不超过60字）指出"
                "最明显的一处视觉异常，例如纹理重复、边缘融合、人体结构异常、光影不一致；"
                "只讲最明显的一点，不要分点或罗列。若没有明显异常，只回答“未见明显异常”。"
                "不要复述分数，不要提及模型或检测方法，不要编造画面中不存在的内容，"
                "不要写“建议人工复核”等套话。"
            ),
        }
    ]
    for frame in frames:
        content.append(
            {"type": "text", "text": f"人脸画面：{_float(frame.get('time')):.1f}s"}
        )
        content.append(
            {"type": "image_url", "image_url": {"url": frame["image"], "detail": "high"}}
        )
    return [{"role": "system", "content": EXPLAIN_SYSTEM_PROMPT}, {"role": "user", "content": content}]


def _merge_explanations(
    result: dict[str, Any],
    jobs: list[tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]]],
    explanations: dict[str, str],
) -> None:
    lines = []
    for person, segment, _ in jobs:
        text = explanations.get(str(segment.get("id")))
        if not text:
            continue
        start = _float(segment.get("start"))
        end = _float(segment.get("end"))
        label = str(person.get("label") or "").strip()
        prefix = f"{label} " if label else ""
        lines.append(f"{prefix}{start:.1f}s–{end:.1f}s：{text}"[:500])
    if not lines:
        return
    result["findings"] = (lines + _strings(result.get("findings")))[:12]


def _clean_explanation(content: Any) -> str:
    if isinstance(content, list):
        content = "".join(
            str(part.get("text", "")) for part in content if isinstance(part, dict)
        )
    text = re.sub(r"\s+", " ", str(content or "")).strip().strip('"').strip("“”").strip()
    text = re.sub(r"(?i)deepseek|vlaforge", "", text).strip()
    text = re.sub(r"^(?:视觉复核|画面复核)[：:]\s*", "", text)
    text = re.sub(r"^(?:[-*•·]|\d+[.、)])\s*", "", text)
    if "人工复核" in text:
        parts = [part for part in re.split(r"[，,；;]", text) if "人工复核" not in part]
        text = "，".join(part.strip() for part in parts if part.strip()).strip()
    if len(text) > MAX_EXPLANATION_CHARS:
        clipped = text[: MAX_EXPLANATION_CHARS - 1]
        boundary = max(clipped.rfind(mark) for mark in "。！？；")
        if boundary >= 20:
            text = clipped[: boundary + 1]
        else:
            text = clipped.rstrip("，,；;。 ") + "。"
    if text and text[-1] not in "。！？!?":
        text += "。"
    return text


def scan_visual_marker(
    frames: list[dict[str, Any]], config: dict[str, Any] | None = None
) -> dict[str, Any]:
    """检查视频画面中是否出现可见的 AI 生成标识；用于直接判定 99%。"""
    if not isinstance(frames, list) or not frames:
        return _visual_status("skipped", reason="no_frames")
    cfg = config or load_config()
    if cfg.get("mode") == "off":
        return _visual_status("disabled")
    if not cfg.get("visual_marker"):
        return _visual_status("disabled", reason="visual_marker_off")
    if not cfg.get("api_key"):
        return _visual_status("not_configured")

    selected = _select_marker_frames(frames, int(cfg["visual_marker_frames"]))
    if not selected:
        return _visual_status("skipped", reason="no_frames")
    started = time.perf_counter()
    results: list[tuple[dict[str, Any], dict[str, Any]]] = []
    errors: list[str] = []
    workers = min(int(cfg["visual_marker_workers"]), len(selected))
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        futures = {pool.submit(_check_visual_marker, cfg, frame): frame for frame in selected}
        for future in as_completed(futures):
            frame = futures[future]
            try:
                result = future.result()
            except Exception as exc:
                message = _safe_error(exc)
                errors.append(message)
                log.warning("画面标识检查失败 frame=%s：%s", frame.get("id"), message)
                continue
            if result is not None:
                results.append((frame, result))

    threshold = float(cfg["visual_marker_confidence"])
    detections = [
        (frame, result)
        for frame, result in results
        if result.get("found") and float(result.get("confidence") or 0.0) >= threshold
    ]
    failed = len(selected) - len(results)
    status = "ok" if failed == 0 else ("partial" if results else "failed")
    payload = _visual_status(
        status,
        detected=False,
        available=len(frames),
        requested=len(selected),
        succeeded=len(results),
        failed=failed,
        durationMs=round((time.perf_counter() - started) * 1000),
        error=errors[0] if errors else "",
    )
    if detections:
        frame, best = max(
            detections, key=lambda item: float(item[1].get("confidence") or 0.0)
        )
        payload.update(
            detected=True,
            time=_float(frame.get("time")),
            text=str(best.get("text") or "")[:200],
            location=str(best.get("location") or "")[:100],
            confidence=round(float(best.get("confidence") or 0.0), 3),
        )
    return payload


def _visual_status(status: str, **extra: Any) -> dict[str, Any]:
    payload = {
        "status": status,
        "detected": False,
        "confidence": 0.0,
        "time": None,
        "text": "",
        "location": "",
    }
    payload.update(extra)
    return payload


def _select_marker_frames(
    frames: list[dict[str, Any]], limit: int
) -> list[dict[str, Any]]:
    valid = [frame for frame in frames if _valid_visual_frame(frame)]
    valid.sort(key=lambda frame: _float(frame.get("time")))
    if len(valid) <= limit:
        return valid
    if limit <= 1:
        return [valid[len(valid) // 2]]
    indexes = sorted(
        {round(index * (len(valid) - 1) / (limit - 1)) for index in range(limit)}
    )
    return [valid[index] for index in indexes]


