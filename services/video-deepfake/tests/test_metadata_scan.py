import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from metadata_scan import scan_video_metadata


def box(box_type: bytes, payload: bytes) -> bytes:
    return (len(payload) + 8).to_bytes(4, "big") + box_type + payload


def mp4_with_comment(comment: str) -> bytes:
    text = comment.encode("utf-8")
    comment_box = box(b"\xa9cmt", len(text).to_bytes(2, "big") + text)
    udta = box(b"udta", comment_box)
    moov = box(b"moov", udta)
    ftyp = box(b"ftyp", b"isomiso2avc1mp41")
    return ftyp + moov


class MetadataScanTests(unittest.TestCase):
    def scan(self, data: bytes, suffix: str = ".mp4"):
        with tempfile.TemporaryDirectory() as folder:
            path = Path(folder) / f"sample{suffix}"
            path.write_bytes(data)
            return scan_video_metadata(path)

    def test_detects_sora_comment(self):
        result = self.scan(mp4_with_comment("Generated by Sora"))
        self.assertTrue(result["detected"])
        self.assertIn("sora", result["markers"])
        self.assertIn("cmt", result["source"])
        self.assertIn("Sora", result["value"])

    def test_detects_chinese_marker(self):
        result = self.scan(mp4_with_comment("本视频由AI生成"))
        self.assertTrue(result["detected"])
        self.assertIn("ai生成", result["markers"])

    def test_ignores_plain_comment(self):
        result = self.scan(mp4_with_comment("Family vacation in the mountains"))
        self.assertFalse(result["detected"])
        self.assertEqual(result["markers"], [])

    def test_does_not_match_tool_name_inside_other_word(self):
        result = self.scan(mp4_with_comment("Sonora desert trip"))
        self.assertFalse(result["detected"])

    def test_fallback_scans_container_strings(self):
        result = self.scan(b"\x00\x01AI-generated video\x00\x02", suffix=".webm")
        self.assertTrue(result["detected"])
        self.assertIn("ai-generated", result["markers"])
        self.assertEqual(result["source"], "container_strings")

    def test_invalid_file_does_not_raise(self):
        result = self.scan(b"\x00" * 32, suffix=".mp4")
        self.assertFalse(result["detected"])
        self.assertIn(result["status"], {"ok", "error"})


if __name__ == "__main__":
    unittest.main()
