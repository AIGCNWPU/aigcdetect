import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(import.meta.url);

// The source-preview import map needs a browser ESM file. Generate it from the
// same locked dependency as esbuild, rather than relying on a local manual copy.
export async function prepareBrowserVendor() {
  const packageDir = path.resolve(path.dirname(require.resolve('fflate')), '..');
  const [module, license, metadata] = await Promise.all([
    readFile(path.join(packageDir, 'esm/browser.js')),
    readFile(path.join(packageDir, 'LICENSE')),
    readFile(path.join(packageDir, 'package.json'), 'utf8'),
  ]);
  const { version } = JSON.parse(metadata);
  const sha256 = createHash('sha256').update(module).digest('hex');
  const output = path.join(root, 'public/vendor/fflate');
  await mkdir(output, { recursive: true });
  await Promise.all([
    writeFile(path.join(output, 'browser.js'), module),
    writeFile(path.join(output, 'LICENSE'), license),
    writeFile(path.join(output, 'README.md'), `# fflate browser module\n\nVersion: ${version}\nSource: installed fflate package, esm/browser.js\nLicense: MIT (see LICENSE)\nSHA256: ${sha256}\n\nGenerated by scripts/prepare-browser-vendor.mjs from the locked npm dependency.\n`),
  ]);
  return { version, sha256 };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { version } = await prepareBrowserVendor();
  console.log(`Prepared browser dependency: fflate ${version}`);
}
